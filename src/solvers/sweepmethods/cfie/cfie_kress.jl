Computes a near-null vector of the CFIE-Kress matrix.

## Description
The CFIE matrix is assembled and passed to
[`smallest_nullvec_krylov!`](@ref).

That routine applies a Krylov eigensolver to the inverse operator, so the
returned scalar is an inverse-eigenvalue-based spectral proximity proxy rather
