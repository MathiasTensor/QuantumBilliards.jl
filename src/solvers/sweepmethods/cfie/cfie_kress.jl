    construct_matrices!(solver,A,pts,Rmat,k;multithreaded=true)
    construct_matrices!(solver,A,A1,A2,pts,ws,k;multithreaded=true)
    construct_matrices!(solver,A,A1,A2,pts,Rmat,k;multithreaded=true)

High-level CFIE-Kress matrix assembly interface.

## Description
These overloads select automatically between full and symmetry-reduced
assembly.

When a cached [`CFIEKressWorkspace`](@ref) is supplied, all geometric quantities
and symmetry maps are reused.

When only `Rmat` is supplied, geometry caches and flattened panel arrays are
constructed from `pts` for the current call.

The assembled operator is

    A(k)=I-(D(k)+ikS(k)).

Derivative overloads additionally return its first two derivatives with respect
to `k`.

## Arguments
* `solver`: CFIE-Kress solver.
* `A`: Destination matrix for the operator.
* `A1`: Destination matrix for the first derivative.
* `A2`: Destination matrix for the second derivative.
* `pts`: Boundary discretizations.
* `ws`: Optional cached CFIE-Kress workspace.
* `Rmat`: Optional precomputed Kress logarithmic correction matrix.
* `basis`: Placeholder Hankel basis used by the common solver API.
* `k`: Real wavenumber.

## Keyword arguments
* `multithreaded`: Whether to thread low-level matrix assembly.

## Returns
* Matrix-only forms return `A`.
* Derivative forms return `(A,A1,A2)`.
"""
function construct_matrices!(solver::Union{CFIE_kress,CFIE_kress_corners,CFIE_kress_global_corners},A::AbstractMatrix{Complex{T}},pts::Vector{BoundaryPoints{T}},ws::CFIEKressWorkspace{T},k::T;multithreaded::Bool=true) where {T<:Real}
    if isnothing(ws.symmetry)
        @blas_1 construct_matrices!(solver,A,pts,ws.Rmat,ws.Gs,ws.parr,ws.offs,k;multithreaded=multithreaded)
    else
        @blas_1 construct_matrices_reduced!(solver,A,pts,ws,k;multithreaded=multithreaded)
    end
    return A
end

