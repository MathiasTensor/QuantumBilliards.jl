Near a genuine simple zero of the Fredholm operator, the corresponding vector
approaches the physical null vector required for boundary-state
postprocessing.

## Arguments
* `solver`: CFIE-Kress solver.
* `basis`: Basis placeholder retained for API compatibility.
* `A`: Optional preallocated matrix buffer.
* `pts`: Boundary discretizations.
* `ws`: Cached CFIE-Kress workspace.
* `billiard`: Billiard geometry, retained by the convenience overload.
* `k`: Real wavenumber.

## Keyword arguments
* `multithreaded`: Whether to thread matrix assembly.
* `tol`: Krylov convergence tolerance.
* `maxiter`: Maximum number of Krylov iterations.
* `krylovdim`: Krylov subspace dimension.

## Returns
* `σ`: Small-eigenvalue/spectral-proximity proxy returned by
  [`smallest_nullvec_krylov!`](@ref).
* `u`: Corresponding normalized near-null vector.
"""
